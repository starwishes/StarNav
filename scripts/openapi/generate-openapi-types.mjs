/* global console, process */
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'

import { generateOpenApiSpec } from './generate-openapi-spec.mjs'

const execFileAsync = promisify(execFile)
const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const REPO_ROOT = path.resolve(__dirname, '../..')
const SPEC_PATH = path.join(REPO_ROOT, 'dist', 'api-docs.json')
const OUTPUT_PATH = path.join(REPO_ROOT, 'src', 'shared', 'types', 'openapi.generated.ts')

const HEADER = `/**
 * AUTO-GENERATED by \`npm run openapi:types\` — do not edit by hand.
 * Source: dist/api-docs.json (from swagger-jsdoc).
 */

`

export const generateOpenApiTypes = async ({
  specPath = SPEC_PATH,
  outputPath = OUTPUT_PATH,
  regenerateSpec = true
} = {}) => {
  if (regenerateSpec) {
    await generateOpenApiSpec(specPath)
  }

  const openapiTypescriptBin = path.join(
    REPO_ROOT,
    'node_modules',
    'openapi-typescript',
    'bin',
    'cli.js'
  )

  await fs.mkdir(path.dirname(outputPath), { recursive: true })

  const { stdout, stderr } = await execFileAsync(
    process.execPath,
    [openapiTypescriptBin, specPath, '--output', outputPath],
    { cwd: REPO_ROOT, maxBuffer: 10 * 1024 * 1024 }
  )

  if (stderr) {
    console.error(stderr.trim())
  }
  if (stdout) {
    console.log(stdout.trim())
  }

  const generated = await fs.readFile(outputPath, 'utf8')
  if (!generated.startsWith('/**')) {
    await fs.writeFile(outputPath, `${HEADER}${generated}`)
  } else if (!generated.includes('AUTO-GENERATED')) {
    await fs.writeFile(outputPath, `${HEADER}${generated}`)
  }

  return outputPath
}

const shouldRunAsScript =
  typeof process.argv[1] === 'string' && import.meta.url === pathToFileURL(process.argv[1]).href

if (shouldRunAsScript) {
  const outputPath = await generateOpenApiTypes()
  console.log(`[openapi:types] wrote ${path.relative(REPO_ROOT, outputPath)}`)
}
